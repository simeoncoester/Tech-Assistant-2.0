# Faceplates measured from the user's product photos (photos only used as measuring templates, drawn anew):
# SSL Fusion, SSL The Bus+, SSL Super 9000, Sound Skulptor CP554, SSL BiG SiX (channel 1 = channel strip, master section).
# Coordinates are pixel positions in the photos; D() converts them to panel fractions.
import sys, json, math

class D:
    def __init__(s, x0, y0, x1, y1, F=10, ink='#ececec'):
        s.x0, s.y0, s.W, s.H, s.F, s.ink = x0, y0, x1 - x0, y1 - y0, F, ink
        s.ar = s.W / s.H; s.d = []; s.c = []
    def P(s, x, y): return [round((x - s.x0) / s.W, 4), round((y - s.y0) / s.H, 4)]
    def sz(s, px): return round(px * 1000 / (s.W * s.F), 3)
    def T(s, x, y, t, px=11, col=None):
        k = s.sz(px); X, Y = s.P(x, y); s.d.append(['txt', X, round(Y + k * s.F * .35 / (1000 / s.ar), 4), t, k, col or s.ink])
    def LBL(s, x, y, rad, ang, t, px=10, col=None):
        a = math.radians(ang); s.T(x + rad * math.sin(a), y - rad * math.cos(a), t, px, col)
    def K(s, name, x, y, dia, col, ext=None, labs=None, rad=None, a0=-150, a1=150, px=10, dots=True, n=None):
        e = dict(ext or {})
        if (a0, a1) != (-135, 135) and 'sweep' not in e: e['sweep'] = [a0, a1]
        s.c.append(['k', name + '|', *s.P(x, y), round(dia / s.W, 4), col, 'n', e])
        rad = rad or dia * .78
        if labs:
            if isinstance(labs[0], (list, tuple)):
                for ang, t in labs:
                    if t: s.LBL(x, y, rad, ang, t, px)
            else:
                s.d.append(['scale', *s.P(x, y), round(rad / s.W, 4), labs, s.sz(px), s.ink, a0, a1])
                if dots: s.d.append(['pdots', *s.P(x, y), round(dia * .62 / s.W, 4), n or len(labs), round(max(2.2, dia * .05) / s.W, 4), s.ink, a0, a1])
    def B(s, name, x, y, size, col='#cfd1d4', cap=None, plain=True, ext=None):
        q = {}
        if plain: q['plain'] = True
        if cap: q['cap'] = cap
        if ext: q.update(ext)
        s.c.append(['p', name + '|', *s.P(x, y), round(size / s.W, 4), col, 'n', q])
    def ST(s, name, x, y, size, col):   # LED state that is toggled on the unit: small round lamp-button
        s.c.append(['p', name + '|', *s.P(x, y), round(size / s.W, 4), col, 'n', {'ps': 'rd'}])
    def LED(s, x, y, dia, col, on=False): s.d.append(['led', *s.P(x, y), round(dia / s.W, 4), col, on])
    def R(s, x, y, w, h, fill, stroke='none', rx=0): s.d.append(['rect', *s.P(x, y), round(w / s.W, 4), round(h / s.H, 4), fill, stroke, rx])
    def SCREW(s, x, y, px=16): s.d.append(['screw', *s.P(x, y), round(px / s.W, 4)])
    def LEDS(s, x, yb, yt, n, dia, col, col2='#ff3b30'): s.d.append(['leds', *s.P(x, yb), *s.P(x, yt), n, round(dia / s.W, 4), col, 0, col2])
    def FAD(s, name, x, marks, col='#2a2b2e'):   # marks: [(label, y)] from top to bottom
        y0, y1 = marks[0][1], marks[-1][1]; L = y1 - y0
        m = [[l, round(1 - (y - y0) / L, 3)] for l, y in marks]
        zero = [p for l, p in m if l == '0'][0]
        s.c.append(['f', name + '|', *s.P(x, (y0 + y1) / 2), round(L / 16.9 / s.W, 4), col, 'n', {'vert': True, 'asp': 18, 'zero': zero, 'dbLabel': False, 'plain': True, 'marks': m}])
    def out(s, **kw):
        n = [q[1] for q in s.c]; assert len(n) == len(set(n)), [x for x in n if n.count(x) > 1]
        e = dict(noEars=True, noTicks=True, ar=round(s.ar, 4), ink=s.ink, fs=s.F, brand='', model='', tx=.5, ty=.03)
        e.update(kw); e['deco'] = s.d; e['c'] = s.c
        return e

